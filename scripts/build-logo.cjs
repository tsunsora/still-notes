// Builds the Still Notes folded-paper mark from exact geometry and writes every icon file:
//   src/icon.svg              light mark used in the app and on dark backgrounds
//   docs/icon-light-mode.svg  ink version for light backgrounds (README on GitHub light theme)
//   src/icon.png              1024px render
//   src/icon.ico              Windows icon, 16-256px
// Run: node scripts/build-logo.cjs
const fs=require('node:fs/promises'),path=require('node:path'),sharp=require('sharp');

// Geometry, in a frame where the bands are horizontal before rotation.
const G={
 length:244,   // band length
 thick:104,    // band thickness; the fold end is a semicircle of half this
 gap:62,       // space between the bands, where the fold shows
 offset:14,    // top band shifts right, bottom band left, to form the S
 radius:24,    // corner radius on the outer ends
 angle:-26,    // rotation in degrees
 fold:.62,     // visible fold width as a share of the run between the two curls
 shadow:12,    // depth of the shadow under the top band's curl
 size:448,pad:20
};
const LIGHT={face:'#EEEEEC',fold:'#969B9D',shadow:'#7E8486'};
// The app's light theme prints the mark with invert(.92); the ink colors match that.
const INK={face:'#232324',fold:'#6C6867',shadow:'#817C7A'};

function mark(colors,title){
 const {length:L,thick:T,gap:g,offset:s,radius:r}=G,R=T/2;
 const top={x0:-L/2+s,x1:L/2+s,y0:-g/2-T,y1:-g/2},bot={x0:-L/2-s,x1:L/2-s,y0:g/2,y1:g/2+T};
 const a=top.x0+R,b=bot.x1-R,w=(b-a)*G.fold,run=b-w-a,k=G.shadow/g,sh=G.shadow;
 const n=v=>+v.toFixed(2);
 const poly=p=>'M'+p.map(([x,y])=>n(x)+' '+n(y)).join('L')+'Z';
 const fold=poly([[a,top.y1],[a+w,top.y1],[b,bot.y0],[b-w,bot.y0]]);
 // One shadow shape: a crescent under the curl flowing into a strip along the fold's top edge.
 const shadow=poly([[a,top.y1],[a+w,top.y1],[a+w+run*k,top.y1+sh],[a+run*k,top.y1+sh]])+
  `M${n(a+run*k)} ${n(top.y1+sh)}L${n(a)} ${n(top.y1+sh)}A${R} ${R} 0 0 1 ${n(a-R)} ${n(top.y1-R+sh)}V${n(top.y1-R)}H${n(a)}Z`;
 const upper=`M${top.x0+R} ${top.y0}H${top.x1-r}A${r} ${r} 0 0 1 ${top.x1} ${top.y0+r}V${top.y1-r}A${r} ${r} 0 0 1 ${top.x1-r} ${top.y1}H${top.x0+R}A${R} ${R} 0 0 1 ${top.x0+R} ${top.y0}Z`;
 const lower=`M${bot.x0+r} ${bot.y0}H${bot.x1-R}A${R} ${R} 0 0 1 ${bot.x1-R} ${bot.y1}H${bot.x0+r}A${r} ${r} 0 0 1 ${bot.x0} ${bot.y1-r}V${bot.y0+r}A${r} ${r} 0 0 1 ${bot.x0+r} ${bot.y0}Z`;
 // Fit the rotated bands into the canvas.
 const th=G.angle*Math.PI/180,pts=[];
 for(const t of [top,bot])for(const x of [t.x0,t.x1])for(const y of [t.y0,t.y1])pts.push([x*Math.cos(th)-y*Math.sin(th),x*Math.sin(th)+y*Math.cos(th)]);
 const xs=pts.map(p=>p[0]),ys=pts.map(p=>p[1]);
 const scale=(G.size-2*G.pad)/Math.max(Math.max(...xs)-Math.min(...xs),Math.max(...ys)-Math.min(...ys));
 const cx=(Math.max(...xs)+Math.min(...xs))/2,cy=(Math.max(...ys)+Math.min(...ys))/2;
 return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${G.size} ${G.size}" fill="none" role="img" aria-labelledby="title">
  <title id="title">${title}</title>
  <!-- Generated by scripts/build-logo.cjs. Two equal paper bands joined by one fold. -->
  <g transform="translate(${G.size/2} ${G.size/2}) scale(${n(scale)}) translate(${n(-cx)} ${n(-cy)}) rotate(${G.angle})">
    <path d="${fold}" fill="${colors.fold}"/>
    <path d="${shadow}" fill="${colors.shadow}"/>
    <path d="${upper}" fill="${colors.face}"/>
    <path d="${lower}" fill="${colors.face}"/>
  </g>
</svg>
`;
}

function ico(images,sizes){
 const header=Buffer.alloc(6+16*sizes.length);header.writeUInt16LE(1,2);header.writeUInt16LE(sizes.length,4);let offset=header.length;
 images.forEach((image,i)=>{const p=6+i*16;header[p]=header[p+1]=sizes[i]===256?0:sizes[i];header.writeUInt16LE(1,p+4);header.writeUInt16LE(32,p+6);header.writeUInt32LE(image.length,p+8);header.writeUInt32LE(offset,p+12);offset+=image.length;});
 return Buffer.concat([header,...images]);
}

(async()=>{
 const root=path.resolve(__dirname,'..'),light=mark(LIGHT,'Still Notes folded-paper logo'),ink=mark(INK,'Still Notes folded-paper logo, ink version for light backgrounds');
 await fs.writeFile(path.join(root,'src/icon.svg'),light);
 await fs.mkdir(path.join(root,'docs'),{recursive:true});await fs.writeFile(path.join(root,'docs/icon-light-mode.svg'),ink);
 const svg=Buffer.from(light),sizes=[16,24,32,48,64,128,256];
 const images=await Promise.all(sizes.map(size=>sharp(svg,{density:Math.max(72,size*72/G.size*4)}).resize(size,size).png().toBuffer()));
 await fs.writeFile(path.join(root,'src/icon.ico'),ico(images,sizes));
 await sharp(svg,{density:300}).resize(1024,1024).png().toFile(path.join(root,'src/icon.png'));
 console.log('Wrote src/icon.svg, docs/icon-light-mode.svg, src/icon.png, src/icon.ico');
})().catch(e=>{console.error(e);process.exit(1);});
